"""
Transfer repository.

All database queries for the transfer domain.
The service layer never writes raw SQL or uses the ORM directly.

Note on UUID generation: transfer IDs are generated in the application
(not the DB) because we need the ID before the insert — it becomes
the outbox event's transfer_id and is used for idempotency checks.
"""

import logging

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.transfer.models import Transfer, TransferStatus

logger = logging.getLogger(__name__)


async def create_transfer(
    session: AsyncSession,
    transfer_id: str,
    sender_wallet_id: int,
    receiver_wallet_id: int,
    amount,
) -> Transfer:
    """
    Insert a new transfer with PENDING status.
    transfer_id is generated by the caller (service layer).
    """
    transfer = Transfer(
        id=transfer_id,
        sender_wallet_id=sender_wallet_id,
        receiver_wallet_id=receiver_wallet_id,
        amount=amount,
        status=TransferStatus.PENDING,
    )
    session.add(transfer)
    await session.flush()

    logger.info(
        "Created transfer id=%s sender=%s receiver=%s amount=%s",
        transfer_id,
        sender_wallet_id,
        receiver_wallet_id,
        amount,
    )
    return transfer


async def get_transfer_by_id(
    session: AsyncSession,
    transfer_id: str,
) -> Transfer | None:
    """
    Fetch a transfer by primary key.
    Returns None if not found.
    """
    result = await session.execute(
        select(Transfer).where(Transfer.id == transfer_id)
    )
    return result.scalar_one_or_none()
